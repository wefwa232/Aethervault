const CACHE = `av-shell-${BUILD}-${HASH}`;

// Install: fetch the whole shell fresh into this version's own cache. All-or-nothing, so a failed
// install leaves the running version untouched. No skipWaiting: the page asks for it (see js/pwa.js).
self.addEventListener('install', e => {
  e.waitUntil(caches.open(CACHE).then(c => c.addAll(PRECACHE.map(u => new Request(u, { cache: 'reload' })))));
});

// Activate: drop caches from every older version.
self.addEventListener('activate', e => {
  e.waitUntil((async () => {
    for (const k of await caches.keys()) if (k.startsWith('av-shell-') && k !== CACHE) await caches.delete(k);
    await self.clients.claim();
  })());
});

// Background Sync (Chromium): the worker holds no credentials. It only wakes an open page, which runs its own normal sync.
self.addEventListener('sync', e => {
  if (e.tag === 'av-cloud-sync') e.waitUntil(self.clients.matchAll({ type: 'window' }).then(cs => cs.forEach(c => c.postMessage({ type: 'CLOUD_SYNC' }))));
});

self.addEventListener('message', e => { if (e.data && e.data.type === 'SKIP_WAITING') self.skipWaiting(); });

// Fetch: shell files are served cache-first from this version's cache, so scripts and styles can never
// mix versions. Everything else (music, logging beacons, other origins) goes straight to the network.
self.addEventListener('fetch', e => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== location.origin) return;
  if (req.mode === 'navigate') {
    e.respondWith(caches.match('index.html', { cacheName: CACHE }).then(r => r || fetch(req)));
    return;
  }
  const path = url.pathname.slice(new URL('./', location.href).pathname.length);
  if (!PRECACHE.includes(path)) return;
  e.respondWith(caches.match(path, { cacheName: CACHE }).then(r => r || fetch(req)));
});
